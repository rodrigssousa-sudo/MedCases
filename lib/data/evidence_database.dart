/// Retorna la evidencia para un fármaco por nombre (normalizado a minúsculas).
/// Busca primero por clave exacta, luego por coincidencia parcial.
DrugEvidenceModel? getGlobalEvidence(String drugName) {
  final key = _normalize(drugName);
  // 1. Exact match
  if (kGlobalEvidenceDB.containsKey(key)) return kGlobalEvidenceDB[key];
  // 2. Partial match — first word
  final first = key.split(' ').first;
  for (final k in kGlobalEvidenceDB.keys) {
    if (k.startsWith(first) || first.startsWith(k)) {
      return kGlobalEvidenceDB[k];
    }
  }
  // 3. Contains
  for (final k in kGlobalEvidenceDB.keys) {
    if (key.contains(k) || k.contains(first)) {
      return kGlobalEvidenceDB[k];
    }
  }
  return null;
}

String _normalize(String s) => s
    .toLowerCase()
    .replaceAll('á', 'a').replaceAll('é', 'e').replaceAll('í', 'i')
    .replaceAll('ó', 'o').replaceAll('ú', 'u').replaceAll('ã', 'a')
    .replaceAll('â', 'a').replaceAll('ê', 'e').replaceAll('ô', 'o')
    .replaceAll('ç', 'c').replaceAll('ñ', 'n')
    .replaceAll(RegExp(r'\(.*?\)'), '').trim();

